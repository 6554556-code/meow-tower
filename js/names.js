// Имена на текущем языке (по умолчанию русские; i18n.js подменит на английские)
const CAT_NAMES = CAT_NAME_PAIRS.map(p => p[0]);

// Переименовать жильцов на текущий язык (вызывается при запуске, после выбора языка).
// Старые сохранения: у кота есть только имя-строка — находим его номер в списке.
function localizeCatNames() {
  state.residents.forEach(r => {
    if (r.nameIdx === undefined) r.nameIdx = CAT_NAME_PAIRS.findIndex(p => p.includes(r.name));
    if (r.nameIdx >= 0 && CAT_NAMES[r.nameIdx]) r.name = CAT_NAMES[r.nameIdx];
    // nameIdx = -1: имени нет в списке (например, удалили) — оставляем как было
  });
}
